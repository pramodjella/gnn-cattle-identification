"""
Main-Track Experiment Orchestrator
==================================
One entry point that runs the full evaluation matrix, collects every result
JSON, and emits a consolidated summary plus a LaTeX table. Training the model
ablations needs your GPU (hours) and is driven separately via config toggles;
this orchestrator prints those exact commands and then aggregates whatever
results are present.

Modes:
    python scripts/run_all_experiments.py --eval        # run all eval scripts
    python scripts/run_all_experiments.py --aggregate   # collect existing JSONs
    python scripts/run_all_experiments.py --plan        # print training matrix

Outputs:
    outputs/stats/main_track_summary.json
    outputs/stats/main_track_tables.tex
"""

import os
import sys
import json
import argparse
import subprocess
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))
PY = sys.executable
STATS = PROJECT_ROOT / 'outputs' / 'stats'

# Fast, checkpoint-only evaluations (no training).
EVAL_STEPS = [
    ('data_integrity', ['scripts/verify_data_integrity.py']),
    ('ensemble', ['scripts/ensemble_inference.py']),
    ('open_set', ['scripts/evaluate_openset.py', '--known-frac', '0.5',
                  '--seeds', '0', '1', '2', '3', '4']),
    ('explainability', ['scripts/evaluate_explainability.py', '--model', 'gnn_v3',
                        '--num-graphs', '40']),
]

# Training ablation matrix (run on your GPU; see docs/IJCB_SUBMISSION_PLAN.md).
ABLATION_MATRIX = [
    ('hybrid_base',        {'multi_scale': False, 'learned_edges': False}),
    ('hybrid_multiscale',  {'multi_scale': True,  'learned_edges': False}),
    ('hybrid_adaptive',    {'multi_scale': False, 'learned_edges': True}),
    ('hybrid_full',        {'multi_scale': True,  'learned_edges': True}),
]


def run_eval():
    for name, cmd in EVAL_STEPS:
        print(f"\n{'#'*70}\n# {name}\n{'#'*70}")
        r = subprocess.run([PY] + cmd, cwd=str(PROJECT_ROOT))
        if r.returncode not in (0, 1):  # integrity returns 1 on failure only
            print(f"  [WARN] {name} exited with code {r.returncode}")


def _load(name):
    p = STATS / name
    if p.exists():
        try:
            return json.loads(p.read_text(encoding='utf-8'))
        except Exception as e:
            print(f"  [WARN] could not parse {name}: {e}")
    return None


def aggregate():
    summary = {}

    di = _load('data_integrity.json')
    if di:
        summary['data_integrity'] = {'all_passed': di.get('all_passed')}

    ens = _load('ensemble_results.json')
    if ens:
        summary['ensemble'] = {
            'test_rank1': ens.get('test_rank1'),
            'eer': ens.get('eer'),
            'roc_auc': ens.get('roc_auc'),
            'val_selected_w_cnn': ens.get('selection', {}).get('val_selected_w_cnn'),
            'selection_gap': ens.get('selection', {}).get('selection_gap'),
        }

    os_ = _load('openset_results.json')
    if os_ and 'aggregated' in os_:
        a = os_['aggregated']
        summary['open_set'] = {
            'known_rank1': a.get('rank1_on_known_probes'),
            'openset_auc': a.get('openset_auc'),
            'DIR@FAR=0.01': a.get('DIR@FAR=0.01'),
            'DIR@FAR=0.05': a.get('DIR@FAR=0.05'),
        }

    fa = _load('explainability_faithfulness.json')
    if fa:
        summary['explainability'] = {
            'methods': {m: {'fidelity_plus': v['fidelity_plus']['mean'],
                            'fidelity_minus': v['fidelity_minus']['mean'],
                            'sparsity': v['sparsity']['mean']}
                        for m, v in fa.get('methods', {}).items()},
            'cross_method_agreement': fa.get('cross_method_agreement', {}).get('mean'),
        }

    cd = _load('cross_dataset_results.json')
    if cd:
        summary['cross_dataset'] = {
            'closed_rank1': cd.get('closed_set', {}).get('rank1'),
            'openset_auc': cd.get('open_set', {}).get('openset_auc', {}).get('mean'),
        }

    abl = _load('ablation_hybrid_variants.json')
    if abl:
        summary['ablation'] = abl

    (STATS / 'main_track_summary.json').write_text(
        json.dumps(summary, indent=2), encoding='utf-8')
    print("\n" + "=" * 70)
    print("  MAIN-TRACK SUMMARY")
    print("=" * 70)
    print(json.dumps(summary, indent=2))
    _emit_latex(summary)
    print("\n  Saved -> outputs/stats/main_track_summary.json")
    print("  Saved -> outputs/stats/main_track_tables.tex")


def _emit_latex(summary):
    lines = [r"% Auto-generated by run_all_experiments.py", ""]
    ens = summary.get('ensemble', {})
    osd = summary.get('open_set', {})
    if ens:
        lines += [
            r"\begin{table}[t]\centering",
            r"\caption{Main results on the primary test split. Ensemble blend "
            r"weight is selected on validation and applied to test.}",
            r"\begin{tabular}{lcccc}\toprule",
            r"Setting & Rank-1 & EER & ROC-AUC & Sel.\ gap\\ \midrule",
            (f"Ensemble & {_pct(ens.get('test_rank1'))} & {_pct(ens.get('eer'))} & "
             f"{_f(ens.get('roc_auc'))} & {_pct(ens.get('selection_gap'))}\\\\"),
            r"\bottomrule\end{tabular}\end{table}", "",
        ]
    if osd:
        def ms(d): return (f"{_pct(d.get('mean'))}$\\pm${_pct(d.get('std'))}"
                           if isinstance(d, dict) else _pct(d))
        lines += [
            r"\begin{table}[t]\centering",
            r"\caption{Open-set evaluation, mean$\pm$std over 5 identity partitions.}",
            r"\begin{tabular}{lc}\toprule",
            r"Metric & Value\\ \midrule",
            f"Rank-1 (known) & {ms(osd.get('known_rank1'))}\\\\",
            f"Open-set AUC & {_f_ms(osd.get('openset_auc'))}\\\\",
            f"DIR@FAR=1\\% & {ms(osd.get('DIR@FAR=0.01'))}\\\\",
            f"DIR@FAR=5\\% & {ms(osd.get('DIR@FAR=0.05'))}\\\\",
            r"\bottomrule\end{tabular}\end{table}",
        ]
    (STATS / 'main_track_tables.tex').write_text("\n".join(lines), encoding='utf-8')


def _pct(x):
    if isinstance(x, dict):
        x = x.get('mean')
    return f"{x*100:.2f}" if isinstance(x, (int, float)) else "--"


def _f(x):
    return f"{x:.4f}" if isinstance(x, (int, float)) else "--"


def _f_ms(d):
    if isinstance(d, dict):
        return f"{_f(d.get('mean'))}$\\pm${_f(d.get('std'))}"
    return _f(d)


def print_plan():
    print("\n" + "=" * 70)
    print("  TRAINING ABLATION MATRIX (run on GPU)")
    print("=" * 70)
    print("  For each variant, set the flags in config.yaml -> hybrid, then:")
    print("    python scripts/train_hybrid.py")
    print("    python scripts/eval_hybrid.py   # writes outputs/stats/hybrid_results.json")
    print()
    for name, flags in ABLATION_MATRIX:
        print(f"  {name:20s}  multi_scale={flags['multi_scale']!s:5s}  "
              f"learned_edges={flags['learned_edges']!s:5s}")
    print("\n  Then collect the four hybrid_results.json into "
          "outputs/stats/ablation_hybrid_variants.json")
    print("  and re-run:  python scripts/run_all_experiments.py --aggregate")
    print("  Full sequence: docs/IJCB_SUBMISSION_PLAN.md")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--eval', action='store_true', help='Run all eval scripts.')
    ap.add_argument('--aggregate', action='store_true', help='Collect result JSONs.')
    ap.add_argument('--plan', action='store_true', help='Print training matrix.')
    args = ap.parse_args()

    if not any([args.eval, args.aggregate, args.plan]):
        args.aggregate = True  # sensible default

    if args.plan:
        print_plan()
    if args.eval:
        run_eval()
    if args.eval or args.aggregate:
        aggregate()


if __name__ == '__main__':
    main()
